#!/usr/bin/env python3
"""Runs the `rehearsal`-tier checks of optiplex.vmTest.checks against the rehearsal VM over ssh.

usage: rehearsal-shim.py CHECKS.py   (env REHEARSAL_SSH: the ssh command prefix, ending with user@host)

CHECKS.py is generated by Nix (packages.x86_64-linux.optiplex-rehearsal-checks-<phase>). It is written against
the NixOS test driver API; this shim provides the subset the snippets may use: `optiplex` with
succeed/fail/execute/wait_until_succeeds/wait_until_fails/wait_for_unit/sleep, and `subtest`.
Commands run as root (sudo) on the VM through bash.
"""
import contextlib
import os
import shlex
import subprocess
import sys
import time


class RequestedAssertionFailed(AssertionError):
    pass


class Host:
    def __init__(self, ssh):
        self.ssh = shlex.split(ssh)

    def execute(self, command, timeout=None):
        remote = "sudo -n bash -c " + shlex.quote("set -o pipefail; " + command)
        r = subprocess.run(
            self.ssh + [remote], capture_output=True, text=True, timeout=timeout
        )
        return r.returncode, r.stdout + r.stderr

    def succeed(self, command, timeout=None):
        print(f"  must succeed: {command}", flush=True)
        rc, out = self.execute(command, timeout)
        if rc != 0:
            raise RequestedAssertionFailed(f"command `{command}` failed (exit code {rc}):\n{out}")
        return out

    def fail(self, command, timeout=None):
        print(f"  must fail: {command}", flush=True)
        rc, out = self.execute(command, timeout)
        if rc == 0:
            raise RequestedAssertionFailed(f"command `{command}` unexpectedly succeeded:\n{out}")
        return out

    def wait_until_succeeds(self, command, timeout=900):
        end = time.time() + timeout
        while True:
            rc, out = self.execute(command)
            if rc == 0:
                return out
            if time.time() > end:
                raise RequestedAssertionFailed(f"timed out waiting for `{command}`:\n{out}")
            time.sleep(1)

    def wait_until_fails(self, command, timeout=900):
        end = time.time() + timeout
        while True:
            rc, out = self.execute(command)
            if rc != 0:
                return out
            if time.time() > end:
                raise RequestedAssertionFailed(f"timed out waiting for `{command}` to fail")
            time.sleep(1)

    def wait_for_unit(self, unit, timeout=900):
        self.wait_until_succeeds(f"systemctl is-active {shlex.quote(unit)}", timeout)

    def sleep(self, secs):
        time.sleep(secs)


failures = []


@contextlib.contextmanager
def subtest(name):
    print(f"subtest: {name}", flush=True)
    try:
        yield
        print(f"  ok: {name}", flush=True)
    except Exception as e:  # noqa: BLE001 - report every failing check, then fail at the end
        print(f"  FAILED: {name}: {e}", flush=True)
        failures.append(name)


def main():
    host = Host(os.environ["REHEARSAL_SSH"])
    code = open(sys.argv[1]).read()
    exec(compile(code, sys.argv[1], "exec"), {"optiplex": host, "subtest": subtest, "log": print})
    if failures:
        print(f"{len(failures)} check(s) failed: {', '.join(failures)}")
        sys.exit(1)
    print("all rehearsal checks passed")


main()
